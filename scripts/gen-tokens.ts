// Generates src/styles/tokens.css (Material 3 color roles) from the seed color.
// Run with: npm run gen:tokens
import { writeFileSync } from "node:fs";
import { registerHooks } from "node:module";
import type { DynamicScheme } from "@material/material-color-utilities";

// The package uses extensionless relative ESM imports, which Node doesn't resolve.
// Retry those with ".js" appended.
registerHooks({
  resolve(specifier, context, nextResolve) {
    try {
      return nextResolve(specifier, context);
    } catch (err) {
      if (specifier.startsWith(".") && !specifier.endsWith(".js")) {
        return nextResolve(`${specifier}.js`, context);
      }
      throw err;
    }
  },
});

const { Hct, MaterialDynamicColors, SchemeTonalSpot, argbFromHex, hexFromArgb } =
  await import("@material/material-color-utilities");

const SEED = "#B5835A"; // warm sand (SPEC §6.1)

const ROLES = [
  "primary",
  "onPrimary",
  "primaryContainer",
  "onPrimaryContainer",
  "secondary",
  "onSecondary",
  "secondaryContainer",
  "onSecondaryContainer",
  "tertiary",
  "onTertiary",
  "tertiaryContainer",
  "onTertiaryContainer",
  "error",
  "onError",
  "errorContainer",
  "onErrorContainer",
  "surface",
  "onSurface",
  "surfaceVariant",
  "onSurfaceVariant",
  "surfaceDim",
  "surfaceBright",
  "surfaceContainerLowest",
  "surfaceContainerLow",
  "surfaceContainer",
  "surfaceContainerHigh",
  "surfaceContainerHighest",
  "inverseSurface",
  "inverseOnSurface",
  "inversePrimary",
  "outline",
  "outlineVariant",
  "shadow",
  "scrim",
] as const;

const kebab = (s: string) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

function vars(scheme: DynamicScheme, indent: string): string {
  return ROLES.map((role) => {
    const color = MaterialDynamicColors[role];
    return `${indent}--md-sys-color-${kebab(role)}: ${hexFromArgb(color.getArgb(scheme))};`;
  }).join("\n");
}

// Hourglass colors (SPEC §6.3): the seed's hue with more chroma so the sand reads as sand,
// at tones that sit well on the light and dark surfaces.
interface SandTones {
  sand: number;
  sandDeep: number;
  glass: number;
  glow: number;
}
const SAND_LIGHT: SandTones = { sand: 74, sandDeep: 64, glass: 55, glow: 80 };
const SAND_DARK: SandTones = { sand: 76, sandDeep: 66, glass: 68, glow: 66 };

function sandVars(tones: SandTones, indent: string): string {
  const hue = Hct.fromInt(argbFromHex(SEED)).hue;
  const color = (chroma: number, tone: number) => hexFromArgb(Hct.from(hue, chroma, tone).toInt());
  return [
    `${indent}--sg-sand: ${color(30, tones.sand)};`,
    `${indent}--sg-sand-deep: ${color(34, tones.sandDeep)};`,
    `${indent}--sg-glass: ${color(10, tones.glass)};`,
    `${indent}--sg-glow: ${color(40, tones.glow)};`,
  ].join("\n");
}

const source = Hct.fromInt(argbFromHex(SEED));
const light = new SchemeTonalSpot(source, false, 0);
const dark = new SchemeTonalSpot(source, true, 0);

const css = `/* Generated by scripts/gen-tokens.ts from seed ${SEED}. Do not edit by hand. */

:root,
:root[data-theme="light"] {
  color-scheme: light;
${vars(light, "  ")}
${sandVars(SAND_LIGHT, "  ")}
}

:root[data-theme="dark"] {
  color-scheme: dark;
${vars(dark, "  ")}
${sandVars(SAND_DARK, "  ")}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${vars(dark, "    ")}
${sandVars(SAND_DARK, "    ")}
  }
}
`;

writeFileSync(new URL("../src/styles/tokens.css", import.meta.url), css);
console.log("Wrote src/styles/tokens.css");
